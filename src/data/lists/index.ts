  seoIntro?: string
  whyItMatters?: string
  faq?: FAQItem[]
  lastReviewedAt?: string
  sponsoredEntry?: RankingEntry
  /** Verweis auf eine vertiefende Seite zum Platz-1-Eintrag, z. B. "Die beste X in Y". */
